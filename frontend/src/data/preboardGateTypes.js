export function normalizePreboardGate(value) {
  return String(value || '').trim().toUpperCase().replace(/\s+/g, '')
}

export function normalizePreboardTerminal(value) {
  const raw = String(value || '').trim().toUpperCase()
  if (!raw) return ''
  const match = raw.match(/^T?([1-4])$/)
  return match ? `T${match[1]}` : raw
}

export function normalizePreboardGateType(value) {
  const raw = String(value || '').trim()
  const found = PREBOARD_GATE_TYPE_OPTIONS.find((item) => item.toLowerCase() === raw.toLowerCase())
  return found || raw
}

export function getPreboardGateTypeClass(gateType) {
  const key = String(gateType || '').trim().toLowerCase()
  return PREBOARD_GATE_TYPE_CLASSES[key] || ''
}

export function readPreboardGateTypeRows() {
  if (typeof localStorage === 'undefined') return PREBOARD_GATE_TYPES
  try {
    const raw = localStorage.getItem(PREBOARD_GATE_TYPE_STORAGE_KEY)
    if (!raw) return PREBOARD_GATE_TYPES
    const parsed = JSON.parse(raw)
    return Array.isArray(parsed) && parsed.length > 0 ? parsed : PREBOARD_GATE_TYPES
  } catch {
    return PREBOARD_GATE_TYPES
  }
}

export function findPreboardGateType(rows, terminal, gate) {
  const normalizedTerminal = normalizePreboardTerminal(terminal)
  const normalizedGate = normalizePreboardGate(gate)
  const exactRow = (rows || []).find((item) => (
    normalizePreboardTerminal(item.terminal) === normalizedTerminal
    && normalizePreboardGate(item.ghr) === normalizedGate
  ))
  if (exactRow) return normalizePreboardGateType(exactRow.gateType)
  const gateOnlyRow = (rows || []).find((item) => normalizePreboardGate(item.ghr) === normalizedGate)
  return gateOnlyRow ? normalizePreboardGateType(gateOnlyRow.gateType) : ''
}
